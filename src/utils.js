const SOUND_MAP = {
  pickup: '/pickup.wav',
  menuPress: '/SoundEffects/menuPresser.mp3',
  ambient: '/SoundEffects/dark-horror-ambience-296781.mp3',
  openingDoor: '/SoundEffects/opening_door.mp3',
  creakingDoor: '/SoundEffects/creaking-door-41706.mp3',
  lockedDoor: '/SoundEffects/trying-to-open-a-locked-door-104302.mp3',
  quizDoor: '/SoundEffects/QuizDoor.mp3',
  safeOpen: '/SoundEffects/Safe_opening.mp3',
  correct: '/SoundEffects/CorrectButton.mp3',
  alarm: '/SoundEffects/alarm-301729.mp3',
  footsteps: '/SoundEffects/heavy-walking-footsteps-352771.mp3',
  monsterRoar: '/SoundEffects/low-monster-roar-97413.mp3',
  rowing: '/SoundEffects/rowingMachine.mp3',
  xpLevel: '/SoundEffects/XpLevelUp.mp3',
};

export function playSound(name = 'pickup', opts = {}) {
  const src = SOUND_MAP[name] || SOUND_MAP.pickup;
  const audio = new Audio(src);
  audio.volume = opts.volume !== undefined ? opts.volume : 0.5;
  if (opts.loop) audio.loop = true;
  audio.play().catch(() => {});
  return audio;
}

export function stopSound(audio) {
  if (audio) {
    audio.pause();
  }
}

export function attachButtonSound() {
  document.addEventListener(
    'click',
    (e) => {
      if (e.target.tagName === 'BUTTON') {
        playSound('menuPress', { volume: 0.3 });
      }
    },
    true
  );
}

// Play a voice over audio clip generated by Bark
export function playVoice(filePath) {
  const audio = new Audio(filePath);
  audio.volume = 1.0;
  audio.play().catch(() => {});
}

// Speak the provided text using Google Text-to-Speech REST API
// Requires VITE_GOOGLE_TTS_KEY environment variable containing an API key
export async function speakText(text) {
  if (typeof fetch === 'undefined') return;
  const apiKey = import.meta.env.VITE_GOOGLE_TTS_KEY;
  if (!apiKey) {
    if ('speechSynthesis' in window) {
      const utterance = new SpeechSynthesisUtterance(text);
      utterance.lang = 'en-GB';
      utterance.rate = 0.8;
      window.speechSynthesis.speak(utterance);
    }
    return;
  }

  try {
    const response = await fetch(
      `https://texttospeech.googleapis.com/v1/text:synthesize?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          input: { text },
          voice: {
            languageCode: 'en-GB',
            name: 'en-GB-Wavenet-B',
            ssmlGender: 'MALE',
          },
          audioConfig: { audioEncoding: 'MP3', speakingRate: 0.8 },
        }),
      }
    );

    const data = await response.json();
    if (data.audioContent) {
      const audio = new Audio(`data:audio/mp3;base64,${data.audioContent}`);
      audio.play().catch(() => {});
    }
  } catch (err) {
    console.error('Failed to speak text with Google TTS', err);
    if ('speechSynthesis' in window) {
      const utterance = new SpeechSynthesisUtterance(text);
      utterance.lang = 'en-GB';
      utterance.rate = 0.8;
      window.speechSynthesis.speak(utterance);
    }
  }
}
