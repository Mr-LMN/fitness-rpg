let globalMuted = false;

export function setMuted(val) {
  globalMuted = !!val;
}

export function isMuted() {
  return globalMuted;
}

export function playSound(name = 'pickup', opts = {}) {
  if (globalMuted) return { pause() {} };
  const src = SOUND_MAP[name] || SOUND_MAP.pickup;
  const audio = new Audio(src);
  audio.volume = opts.volume !== undefined ? opts.volume : 0.5;
  if (opts.loop) audio.loop = true;
  audio.play().catch(() => {});
  return audio;
}

export function stopSound(audio) {
  if (audio) {
    audio.pause();
  }
}

export function attachButtonSound() {
  document.addEventListener(
    'click',
    (e) => {
      if (e.target.tagName === 'BUTTON') {
        playSound('menuPress', { volume: 0.3 });
      }
    },
    true
  );
}

// Play a voice over audio clip generated by Bark
export function playVoice(filePath) {
  if (globalMuted) return;
  const audio = new Audio(filePath);
  audio.volume = 1.0;
  audio.play().catch(() => {});
}

// Speak text using the backend /speak endpoint which proxies Google TTS
export async function speakText(text) {
  if (globalMuted || typeof fetch === 'undefined') return;

  try {
    const response = await fetch('/speak', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, voice: 'en-GB-Wavenet-D' }),
    });
    if (!response.ok) throw new Error('TTS request failed');

    // Try handling both raw blobs and JSON { audioContent }
    const contentType = response.headers.get('Content-Type') || '';
    let audioUrl = null;

    if (contentType.includes('application/json')) {
      const data = await response.json();
      if (data.audioContent) {
        audioUrl = `data:audio/mp3;base64,${data.audioContent}`;
      }
    } else {
      const blob = await response.blob();
      audioUrl = URL.createObjectURL(blob);
    }

    if (audioUrl) {
      const audio = new Audio(audioUrl);
      audio.play().catch(() => {});
    } else if ('speechSynthesis' in window) {
      const utterance = new SpeechSynthesisUtterance(text);
      utterance.lang = 'en-GB';
      utterance.rate = 0.8;
      window.speechSynthesis.speak(utterance);
    }
  } catch (err) {
    console.error('Failed to speak text via backend', err);
    if ('speechSynthesis' in window) {
      const utterance = new SpeechSynthesisUtterance(text);
      utterance.lang = 'en-GB';
      utterance.rate = 0.8;
      window.speechSynthesis.speak(utterance);
    }
  }
}

/**
 * Estimate calories burned using MET, weight, and duration or reps/sets.
 * @param {Object} exercise - The exercise object (must include `met`)
 * @param {number} userWeightKg - Student weight in kg (default = 50)
 * @param {number} durationMin - For cardio or time-based movements
 * @param {number} sets - For strength exercises
 * @param {number} reps - For strength exercises
 * @param {number} weightLiftedPerRep - In kg (for weighted strength moves)
 * @returns {number} Estimated calories burned
 */
export function estimateCalories({
  exercise,
  userWeightKg = 50,
  durationMin = 0,
  sets = 0,
  reps = 0,
  weightLiftedPerRep = 0,
}) {
  const met = exercise.met || 0;

  if (durationMin > 0) {
    // Cardio or timed movement
    return +(met * userWeightKg * (durationMin / 60)).toFixed(1);
  }

  if (sets > 0 && reps > 0) {
    const estimatedTimeMin = (sets * reps * 3) / 60; // Assume ~3 seconds per rep
    const adjustedMet = met || 4.0;
    return +(adjustedMet * userWeightKg * (estimatedTimeMin / 60)).toFixed(1);
  }

  return 0; // Unknown case
}

export function updateLifetimeSummary({ weightLifted = 0, distance = 0, calories = 0, bossesDefeated = 0 }) {
  const data = JSON.parse(localStorage.getItem('lifetimeSummary') || '{}');
  data.workouts = (data.workouts || 0) + 1;
  data.weightLifted = +(data.weightLifted || 0) + weightLifted;
  data.distance = +(data.distance || 0) + distance;
  data.calories = +(data.calories || 0) + calories;
  data.bossesDefeated = (data.bossesDefeated || 0) + bossesDefeated;
  localStorage.setItem('lifetimeSummary', JSON.stringify(data));
}

